def qid(subtest: str, n: int) -> str:
    return f"{subtest}-{n:03d}"


def hint4(kilat, eliminasi, logika, jebakan):
    return [
        {"lens": "kilat", "text": kilat},
        {"lens": "eliminasi", "text": eliminasi},
        {"lens": "logika", "text": logika},
        {"lens": "jebakan", "text": jebakan},
    ]


def make(pid, subtest, topic, stem, options, key, weights, hints, explain, target_sec):
    q = {
        "id": qid(subtest, pid),
        "subtest": subtest,
        "topic": topic,
        "stem": stem,
        "options": options,
        "hints": hints,
        "explain": explain,
        "targetSec": target_sec,
    }
    if weights is not None:
        q["weights"] = weights
    else:
        q["key"] = key
    return q


